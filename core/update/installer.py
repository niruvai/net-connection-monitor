"""Hands a verified download to the operating system's installer, then lets the app exit.

* Windows: runs the Inno Setup installer silently. Its Restart Manager support closes any
  leftover copy of the app and the installer relaunches it afterwards.
* macOS: a detached shell script waits for this process to exit, mounts the DMG, verifies the new
  bundle's code signature and version, swaps the .app atomically (rolling back on any failure) and
  reopens it. When the app is not in a writable location the DMG is simply opened for drag-and-drop.

User data (settings, history, logs) lives outside the install location, so none of this touches it.
"""
from __future__ import annotations

import logging
import os
import shlex
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from utils.paths import is_frozen, logs_dir

log = logging.getLogger(__name__)

APP_BUNDLE_NAME = "Net Watcher.app"
WINDOWS_ARGS = ["/SILENT", "/SUPPRESSMSGBOXES", "/NORESTART", "/CLOSEAPPLICATIONS", "/NWUPDATE=1"]


class InstallError(Exception):
    pass


@dataclass
class InstallPlan:
    kind: str  # "windows-installer" | "macos-swap" | "macos-manual"
    command: list[str]
    quits_app: bool = True  # False when the user finishes manually (macOS drag-and-drop)
    script: str = ""
    message: str = ""
    env: dict[str, str] = field(default_factory=dict)


def windows_command(installer: Path) -> list[str]:
    return [str(installer), *WINDOWS_ARGS]


def current_app_bundle(executable: str | None = None) -> Path | None:
    """``/Applications/Net Watcher.app`` when running from a bundle, else None."""
    exe = Path(executable or sys.executable).resolve()
    for parent in exe.parents:
        if parent.suffix == ".app" and parent.is_dir():
            return parent
    return None


def macos_script(dmg: Path, app: Path, pid: int, expected_version: str, log_file: Path) -> str:
    q = shlex.quote
    return f"""#!/bin/sh
# Generated by Net Watcher's updater. Safe to delete after it has run.
PID={int(pid)}
DMG={q(str(dmg))}
APP={q(str(app))}
APP_NAME={q(app.name)}
EXPECTED={q(expected_version)}
LOG={q(str(log_file))}
exec >>"$LOG" 2>&1
echo "=== update to $EXPECTED started $(date) ==="

NEW="$APP.update-new"
OLD="$APP.update-old"
MNT=""

cleanup() {{
    rm -rf "$NEW"
    if [ -n "$MNT" ]; then
        hdiutil detach "$MNT" -quiet -force
        rmdir "$MNT" 2>/dev/null
    fi
}}
trap cleanup EXIT

fail() {{
    echo "UPDATE FAILED: $1"
    [ -d "$OLD" ] && [ ! -d "$APP" ] && mv "$OLD" "$APP"
    open "$APP"
    exit 1
}}

i=0
while kill -0 "$PID" 2>/dev/null; do
    i=$((i + 1))
    [ "$i" -gt 120 ] && fail "old app did not quit"
    sleep 0.5
done

MNT=$(mktemp -d /tmp/netwatcher-update.XXXXXX) || fail "no temp dir"
hdiutil attach "$DMG" -nobrowse -readonly -noautoopen -mountpoint "$MNT" || fail "could not mount DMG"
SRC="$MNT/$APP_NAME"
[ -d "$SRC" ] || fail "DMG does not contain $APP_NAME"

rm -rf "$NEW" "$OLD"
ditto "$SRC" "$NEW" || fail "copy failed"
codesign --verify --deep --strict "$NEW" || fail "code signature check failed"
FOUND=$(defaults read "$NEW/Contents/Info" CFBundleShortVersionString 2>/dev/null)
[ "$FOUND" = "$EXPECTED" ] || fail "version mismatch (found '$FOUND')"

mv "$APP" "$OLD" || fail "could not move old app aside"
mv "$NEW" "$APP" || fail "could not move new app into place"
rm -rf "$OLD"
echo "update installed; relaunching"
open "$APP"
rm -f "$DMG"
"""


def plan_install(installer: Path, version: str, platform_key: str, pid: int | None = None) -> InstallPlan:
    if not installer.is_file():
        raise InstallError("The downloaded update is missing.")
    family = platform_key.split("-")[0]
    if family == "windows":
        return InstallPlan("windows-installer", windows_command(installer), message="Installing the update…")
    if family == "macos":
        app = current_app_bundle() if is_frozen() else None
        if app is not None and os.access(app.parent, os.W_OK) and os.access(app, os.W_OK):
            script_path = installer.with_suffix(".sh")
            script = macos_script(installer, app, pid or os.getpid(), version, logs_dir() / "update-install.log")
            return InstallPlan(
                "macos-swap", ["/bin/sh", str(script_path)], script=script, message="Installing the update…"
            )
        return InstallPlan(
            "macos-manual",
            ["open", str(installer)],
            quits_app=False,
            message="The update disk image was opened. Drag Net Watcher into Applications to finish.",
        )
    raise InstallError("Automatic installation is not supported on this operating system.")


def launch(plan: InstallPlan) -> None:
    """Start the installer detached from this process so it survives our exit."""
    try:
        if plan.script:
            script_path = Path(plan.command[-1])
            script_path.write_text(plan.script, encoding="utf-8")
            script_path.chmod(0o700)
        kwargs: dict = {"stdin": subprocess.DEVNULL, "stdout": subprocess.DEVNULL, "stderr": subprocess.DEVNULL}
        if sys.platform == "win32":
            kwargs["creationflags"] = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
            kwargs["close_fds"] = True
        else:
            kwargs["start_new_session"] = True
        log.info("Launching installer: %s", " ".join(plan.command))
        subprocess.Popen(plan.command, **kwargs)
    except OSError as exc:
        raise InstallError(f"Could not start the installer: {exc}") from exc
